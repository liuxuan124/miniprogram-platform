def to_html(blocks):
    out = []
    for tag, text in blocks:
        if tag == "h3":
            out.append("<h3>%s</h3>" % text)
        else:
            out.append("<p>%s</p>" % text)
    return "".join(out)


def build():
    """生成 xhs_merged_notes.json"""
    items = []
    for topic, cfg in MERGED_NOTES.items():
        items.append({
            "topic": topic,
            "title": cfg["title"],
            "summary": cfg["summary"],
            "content": to_html(cfg["body"]),
            "tags": cfg["tags"],
            "categoryName": cfg["category"],
            "merge_mode": "多图合并",
        })
    p = Path(__file__).parent / "xhs_merged_notes.json"
    p.write_text(json.dumps({"notes": items}, ensure_ascii=False, indent=2),
                 encoding="utf-8")
    print("生成 %d 条合并笔记 -> %s" % (len(items), p.name))
    for n in items:
        txt = re.sub(r"<[^>]+>", "", n["content"])
        print("  【%s】%s" % (n["topic"], n["title"]))
        print("     摘要 %d 字 | 正文 %d 字 | %d 个小节"
              % (len(n["summary"]), len(txt), n["content"].count("<h3>")))
    return items


if __name__ == "__main__":
    build()
